"""Evaluate the shipped checkpoint on the Food-101 test split.

Food-101 ships a fixed train/test split: 750 training and 250 test images per
class, 25,250 test images in total. The test labels were never used during
training, so this is the number worth publishing.

The script imports the transform from `app.preprocessing`, so it measures the
served model rather than an idealised variant of it.

Usage:

    python evaluation/evaluate.py --data-dir ./data --output evaluation/RESULTS.md

On first run this downloads Food-101 (~5GB). On a Colab T4 the full test split
takes roughly 10-15 minutes at batch size 64.
"""

from __future__ import annotations

import argparse
import json
import platform
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

import torch
from torch.utils.data import DataLoader
from torchvision.datasets import Food101

from app.model import load_classes, load_model, select_device
from app.preprocessing import inference_transform


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", default="./data", help="Food-101 download location")
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--num-workers", type=int, default=2)
    parser.add_argument("--limit", type=int, default=None, help="Stop after N batches (smoke runs)")
    parser.add_argument("--output", default="evaluation/RESULTS.md")
    parser.add_argument("--json-output", default="evaluation/results.json")
    return parser.parse_args()


def evaluate(model, loader, device, classes, limit=None):
    top1 = top5 = total = 0
    per_class_correct: dict[int, int] = defaultdict(int)
    per_class_total: dict[int, int] = defaultdict(int)
    confusions: dict[tuple[int, int], int] = defaultdict(int)

    with torch.no_grad():
        for batch_index, (images, targets) in enumerate(loader):
            if limit is not None and batch_index >= limit:
                break
            images, targets = images.to(device), targets.to(device)
            logits = model(images)
            ranked = logits.topk(5, dim=1).indices

            predicted = ranked[:, 0]
            hits1 = predicted == targets
            hits5 = (ranked == targets.unsqueeze(1)).any(dim=1)

            top1 += int(hits1.sum())
            top5 += int(hits5.sum())
            total += targets.size(0)

            for target, prediction, hit in zip(
                targets.tolist(), predicted.tolist(), hits1.tolist(), strict=True
            ):
                per_class_total[target] += 1
                if hit:
                    per_class_correct[target] += 1
                else:
                    confusions[(target, prediction)] += 1

    per_class = {
        classes[index]: per_class_correct[index] / per_class_total[index]
        for index in sorted(per_class_total)
    }
    top_confusions = [
        {"true": classes[t], "predicted": classes[p], "count": count}
        for (t, p), count in sorted(confusions.items(), key=lambda kv: -kv[1])[:15]
    ]
    return {
        "images": total,
        "top1": top1 / total if total else 0.0,
        "top5": top5 / total if total else 0.0,
        "per_class_accuracy": per_class,
        "top_confusions": top_confusions,
    }


def write_report(results: dict, path: Path, device: torch.device, partial: bool) -> None:
    per_class = results["per_class_accuracy"]
    ranked = sorted(per_class.items(), key=lambda kv: kv[1], reverse=True)
    lines = [
        "# Evaluation results",
        "",
        f"Generated by `evaluation/evaluate.py` on "
        f"{datetime.now(timezone.utc).date().isoformat()}.",
        "",
        "Measured on the official Food-101 test split, using the same preprocessing",
        "transform the API applies at inference time (`app/preprocessing.py`).",
        "",
    ]
    if partial:
        lines += [
            "> **Partial run.** `--limit` was set, so this covers a subset of the test",
            "> split and should not be quoted as the headline number.",
            "",
        ]
    lines += [
        "## Headline",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Test images | {results['images']:,} |",
        f"| Top-1 accuracy | {results['top1'] * 100:.2f}% |",
        f"| Top-5 accuracy | {results['top5'] * 100:.2f}% |",
        f"| Device | {device.type} |",
        f"| Platform | {platform.platform()} |",
        "",
        "## Strongest classes",
        "",
        "| Class | Top-1 |",
        "| --- | --- |",
    ]
    lines += [f"| {name} | {acc * 100:.1f}% |" for name, acc in ranked[:10]]
    lines += ["", "## Weakest classes", "", "| Class | Top-1 |", "| --- | --- |"]
    lines += [f"| {name} | {acc * 100:.1f}% |" for name, acc in ranked[-10:]]
    lines += [
        "",
        "## Most frequent confusions",
        "",
        "| True class | Predicted as | Count |",
        "| --- | --- | --- |",
    ]
    lines += [
        f"| {c['true']} | {c['predicted']} | {c['count']} |"
        for c in results["top_confusions"]
    ]
    lines += ["", "Regenerate with `python evaluation/evaluate.py`.", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    args = parse_args()
    device = select_device()
    classes = load_classes()
    model = load_model(device)

    dataset = Food101(
        root=args.data_dir, split="test", transform=inference_transform(), download=True
    )
    if [name.lower() for name in dataset.classes] != [c.lower() for c in classes]:
        raise SystemExit(
            "model/classes.json does not match torchvision's Food101 class order; "
            "labels would be silently wrong"
        )

    loader = DataLoader(
        dataset,
        batch_size=args.batch_size,
        shuffle=False,
        num_workers=args.num_workers,
        pin_memory=device.type == "cuda",
    )

    results = evaluate(model, loader, device, classes, limit=args.limit)
    print(f"images={results['images']}  top1={results['top1']:.4f}  top5={results['top5']:.4f}")

    Path(args.json_output).write_text(json.dumps(results, indent=2), encoding="utf-8")
    write_report(results, Path(args.output), device, partial=args.limit is not None)


if __name__ == "__main__":
    main()
