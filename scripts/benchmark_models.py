"""A/B: CPU serving cost of the two architectures this project has shipped.

Accuracy for both is measured on the real Food-101 test split (training/README.md:
v1.1.0 ResNet-50 82.19%, v2.0.0 ConvNeXt-Tiny 91.89%). This script adds the
other half of the trade-off without any checkpoint or GPU: parameter count,
float32 checkpoint size, and single-image CPU latency through the exact serving
path (prepare -> classify_tensor). Weights are random; latency does not depend
on their values.

    python scripts/benchmark_models.py --runs 30 --out evaluation/AB_LATENCY.md
"""

from __future__ import annotations

import argparse
import io
import platform
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import timm  # noqa: E402
import torch  # noqa: E402
from PIL import Image  # noqa: E402

from app.model import load_classes  # noqa: E402
from app.predict import classify_tensor  # noqa: E402
from app.preprocessing import prepare  # noqa: E402

# label -> (timm name, published top-1, published top-5)
CANDIDATES = {
    "A: resnet50 (v1.1.0)": ("resnet50", 82.19, 96.27),
    "B: convnext_tiny (v2.0.0, served)": ("convnext_tiny.fb_in22k_ft_in1k", 91.89, 98.76),
}


def _image_bytes() -> bytes:
    buffer = io.BytesIO()
    Image.new("RGB", (512, 384), "orange").save(buffer, format="JPEG")
    return buffer.getvalue()


def benchmark(model_name: str, runs: int, warmup: int) -> dict[str, float]:
    """Measure size and latency of one architecture through the serving path."""
    torch.manual_seed(0)
    model = timm.create_model(model_name, pretrained=False, num_classes=len(load_classes()))
    model.eval()
    params = sum(p.numel() for p in model.parameters())
    size_mb = sum(t.numel() * t.element_size() for t in model.state_dict().values()) / 1e6
    raw = _image_bytes()
    device = torch.device("cpu")
    for _ in range(warmup):
        classify_tensor(prepare(io.BytesIO(raw)), model, device, top_k=5)
    timings = []
    for _ in range(runs):
        start = time.perf_counter()
        classify_tensor(prepare(io.BytesIO(raw)), model, device, top_k=5)
        timings.append((time.perf_counter() - start) * 1000)
    timings.sort()
    return {
        "params_m": params / 1e6,
        "size_mb": size_mb,
        "p50_ms": statistics.median(timings),
        "p90_ms": timings[int(0.9 * (len(timings) - 1))],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="CPU serving-cost A/B of shipped models")
    parser.add_argument("--runs", type=int, default=30)
    parser.add_argument("--warmup", type=int, default=5)
    parser.add_argument("--threads", type=int, default=4)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args()
    torch.set_num_threads(args.threads)

    lines = [
        "# A/B: ResNet-50 vs ConvNeXt-Tiny serving cost",
        "",
        f"Generated by `python scripts/benchmark_models.py --runs {args.runs} "
        f"--threads {args.threads}` on {platform.system()} {platform.machine()}, "
        f"torch {torch.__version__}, CPU only.",
        "",
        "Accuracy columns are the published Food-101 test-split numbers (25,250 images).",
        "Latency is one 512x384 JPEG through `prepare` + `classify_tensor`",
        "(decode, transform, forward pass, top-5). Absolute numbers depend on the machine;",
        "the ratio between the rows is the useful part.",
        "",
        "| Variant | Params | float32 size | CPU p50 | CPU p90 | Top-1 | Top-5 |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for label, (name, top1, top5) in CANDIDATES.items():
        r = benchmark(name, args.runs, args.warmup)
        lines.append(
            f"| {label} | {r['params_m']:.1f}M | {r['size_mb']:.0f}MB | {r['p50_ms']:.0f} ms"
            f" | {r['p90_ms']:.0f} ms | {top1:.2f}% | {top5:.2f}% |"
        )
        print(lines[-1], flush=True)
    report = "\n".join(lines) + "\n"
    if args.out:
        args.out.write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
